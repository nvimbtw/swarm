"""Convert the companion artwork into pixel-art animation frames.

Reads public/companion/<pose>-128.webp (input only, never written) and writes
src/components/ui/companion-frames.ts. Run from Frontend/ after the artwork
changes:  python scripts/companion-ascii.py   (needs: pip install pillow)

Each pose keeps its original colours: the art is reduced to a small palette,
and every frame is text with one palette key per pixel (a space is empty),
the same colour-key idea as the vendored ascii-magic kit.

The art is one still per pose, so motion is derived: each frame samples the
image up to one pixel lower, which makes the character bob while every frame
keeps the same size.
"""
import json
from collections import Counter
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
POSES = ['generating', 'request-sent', 'request-received', 'away', 'completed', 'offline']
KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'  # the ascii-magic kit's colour keys
COLORS = 32  # enough that small accents like the green screen light survive
SIZES = {'large': 32, 'small': 16}  # pixels per side
BOB = [0, 0.5, 1, 0.5]  # vertical sample offset per frame, in pixels


def square(pose: str) -> Image.Image:
    art = Image.open(ROOT / 'public' / 'companion' / f'{pose}-128.webp').convert('RGBA')
    # Centre on a square canvas (as object-contain did) so every pose shares one grid.
    side = max(art.size)
    im = Image.new('RGBA', (side, side))
    im.paste(art, ((side - art.width) // 2, (side - art.height) // 2))
    return im


def palette(im: Image.Image) -> tuple[list[str], list[int | None]]:
    """The pose's main colours, and each source pixel's palette index (None where transparent)."""
    pixels = list(im.getdata())
    solid = [p[:3] for p in pixels if p[3] > 128]
    strip = Image.new('RGB', (len(solid), 1))
    strip.putdata(solid)
    reduced = strip.quantize(COLORS, dither=Image.Dither.NONE)
    rgb = reduced.getpalette()[: COLORS * 3]
    indexes = iter(reduced.getdata())
    owner = [next(indexes) if p[3] > 128 else None for p in pixels]
    return [f'#{rgb[i]:02x}{rgb[i + 1]:02x}{rgb[i + 2]:02x}' for i in range(0, len(rgb), 3)], owner


def frame(size: int, owner: list[int | None], pixels: int, dy: float) -> str:
    cell = size / pixels
    lines = []
    for r in range(pixels):
        line = ''
        for c in range(pixels):
            samples = [
                owner[y * size + x]
                for y in range(int((r + dy) * cell), int((r + 1 + dy) * cell))
                for x in range(int(c * cell), int((c + 1) * cell))
                if 0 <= y < size
            ]
            solid = [s for s in samples if s is not None]
            # The cell's most common colour keeps edges crisp instead of blending them.
            line += KEYS[Counter(solid).most_common(1)[0][0]] if len(solid) >= 0.35 * max(1, len(samples)) and solid else ' '
        lines.append(line)
    return '\n'.join(lines)


def main() -> None:
    out = ['// Generated by scripts/companion-ascii.py from public/companion. Do not edit by hand.',
           "import type { CompanionPose } from '../../data/fixtures'", '',
           '/** Per pose: its palette, and frames with one palette key per pixel (space = empty). */',
           'export const COMPANION_ART: Record<',
           "  'large' | 'small',",
           '  Record<CompanionPose, { palette: string[]; frames: string[] }>',
           '> = {']
    art = {pose: square(pose) for pose in POSES}
    colors = {pose: palette(im) for pose, im in art.items()}
    for set_name, pixels in SIZES.items():
        out.append(f'  {set_name}: {{')
        for pose in POSES:
            hexes, owner = colors[pose]
            frames = [frame(art[pose].width, owner, pixels, dy) for dy in BOB]
            assert all(len(line) == pixels for f in frames for line in f.split('\n')), pose
            out.append(f"    '{pose}': {{")
            out.append(f'      palette: {json.dumps(hexes)},')
            out.append('      frames: [')
            out += [f'        {json.dumps(f)},' for f in frames]
            out.append('      ],')
            out.append('    },')
        out.append('  },')
    out.append('}')
    (ROOT / 'src' / 'components' / 'ui' / 'companion-frames.ts').write_text('\n'.join(out) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
